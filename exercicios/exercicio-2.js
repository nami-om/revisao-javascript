let a = 0, b = 0

a = Number(prompt("Digite o primeiro número:"))
b = Number(prompt("Digite o segundo número:"))

let adicao = a + b, subtracao = a - b, multiplicacao = a * b, divisao = a / b

console.log(a + "+" + b + " = " + adicao)
console.log(a + "-" + b + " = " + subtracao)
console.log(a + "x" + b + " = " + multiplicacao)
console.log(a + "/" + b + " = " + divisao)

